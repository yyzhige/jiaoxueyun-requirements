function unionDecisionAffected(decisionAffected) {
  return affected(Object.fromEntries(AFFECTED_KEYS.map((affectedKey) => [
    affectedKey,
    [...new Set(Object.values(decisionAffected).flatMap((source) => (
      source.affected[affectedKey]
    )))],
  ])));
}

export const migrationChanges = deepFreeze(migrationGroups.map((group) => {
  const decisionAffected = decisionAffectedByMigrationId[group.id];
  const declaredDecisionIds = Object.keys(decisionAffected ?? {});
  if (
    !decisionAffected
    || declaredDecisionIds.length !== group.decisionIds.length
    || group.decisionIds.some((decisionId) => !Object.hasOwn(decisionAffected, decisionId))
    || declaredDecisionIds.some((decisionId) => !group.decisionIds.includes(decisionId))
  ) {
    throw new Error(`${group.id} must declare exact per-decision affected and applicability truth`);
  }
  return {
    ...group,
    affected: unionDecisionAffected(decisionAffected),
    decisionAffected,
  };
}));
