function explicitDecisionImpact(decisionId, affectedValues, applicableAxes) {
  const exactAffected = affected(affectedValues);
  const applicable = new Set(applicableAxes);
  const unknownAxes = [...applicable].filter((axisKey) => !TRACE_AXIS_KEYS.includes(axisKey));
  if (unknownAxes.length > 0) {
    throw new Error(`${decisionId} declares unsupported trace axes: ${unknownAxes.join(", ")}`);
  }
  const axisApplicability = Object.fromEntries(TRACE_AXIS_KEYS.map((axisKey) => {
    const [applicableReasonCode, notApplicableReasonCode, label] = TRACE_AXIS_REASON[axisKey];
    const sourceKey = AFFECTED_KEY_BY_TRACE_AXIS[axisKey];
    const hasReferences = exactAffected[sourceKey].length > 0;
    if (applicable.has(axisKey) !== hasReferences) {
      throw new Error(`${decisionId}.${axisKey} explicit applicability must match its declared source references`);
    }
    return [axisKey, applicable.has(axisKey) ? {
      status: "APPLICABLE",
      reasonCode: applicableReasonCode,
      reason: `${decisionId} 直接改变${label}合同，必须追踪本决策声明的精确引用。`,
    } : {
      status: "NOT_APPLICABLE",
      reasonCode: notApplicableReasonCode,
      reason: `${decisionId} 不直接改变${label}合同；不得由其他决策的引用并集推定为适用。`,
    }];
  }));
  return { affected: exactAffected, axisApplicability };
}

const migrationGroupById = new Map(migrationGroups.map((group) => [group.id, group]));

function wholeGroupDecisionImpact(migrationId, decisionId, applicableAxes, additions = {}) {
  const group = migrationGroupById.get(migrationId);
  if (!group) throw new Error(`missing migration group ${migrationId}`);
  return explicitDecisionImpact(decisionId, Object.fromEntries(AFFECTED_KEYS.map((affectedKey) => [
    affectedKey,
    [...new Set([
      ...(group.affected[affectedKey] ?? []),
      ...(additions[affectedKey] ?? []),
    ])],
  ])), applicableAxes);
}

