function optionSet(id, key, label, entries) {
  return {
    id,
    key,
    label,
    mode: "STATIC",
    values: entries.map(([code, valueLabel, metadata]) => ({
      code,
      label: valueLabel,
      ...(metadata ?? {}),
    })),
  };
}

function runtimeOptionSet(
  id,
  key,
  label,
  queryId,
  filterContext,
  idKind = "OBJECT_ID",
) {
  return {
    id,
    key,
    label,
    mode: "RUNTIME_QUERY",
    values: [],
    source: {
      queryId,
      idKind,
      valueField: idKind === "ACTION_ID" ? "actionId" : "objectId",
      labelField: "displayName",
      labelSnapshot: true,
      filterContext,
    },
  };
}

