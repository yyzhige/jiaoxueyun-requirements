function ensureDir(filePath) {
  fs.mkdirSync(path.dirname(filePath), { recursive: true });
}

function write(relPath, content) {
  const absPath = path.join(root, relPath);
  ensureDir(absPath);
  fs.writeFileSync(absPath, `${content.trimEnd()}\n`, "utf8");
}

function mdTable(headers, rows) {
  const head = `| ${headers.join(" | ")} |`;
  const sep = `| ${headers.map(() => "---").join(" | ")} |`;
  const body = rows.map((row) => `| ${row.map((v) => String(v ?? "").replace(/\n/g, "<br>")).join(" | ")} |`);
  return [head, sep, ...body].join("\n");
}

function list(items) {
  return items.map((item) => `- ${item}`).join("\n");
}

function numbered(items) {
  return items.map((item, index) => `${index + 1}. ${item}`).join("\n");
}

function slugIndex(moduleId) {
  const n = modules.findIndex((m) => m.id === moduleId) + 1;
  return String(n).padStart(2, "0");
}

function prdPath(m) {
  return `${packageRoot}/03-full-prd-md/${slugIndex(m.id)}-${m.slug}_PRD_v2.0.md`;
}

function wirePath(m) {
  return `${packageRoot}/05-wireframe-contracts/${slugIndex(m.id)}-${m.slug}-wireframe.zh-CN.md`;
}

function modulePrefix(m) {
  return m.id.split("-")[0];
}

